const DICTS: Record<LanguageCode, Dict> = { en, es, fr, zh, ar, vi };

/** Returns a translator function `tr(key)` bound to the given language, falling back to English. */
export const t = (lang: LanguageCode) => {
  const dict = DICTS[lang] || en;
  return (key: string, vars?: Record<string, string | number>): string => {
    let str = dict[key] ?? en[key] ?? key;
    if (vars) {
      Object.entries(vars).forEach(([k, v]) => {
        str = str.replace(`{${k}}`, String(v));
      });
    }
    return str;
  };
};

/** Splits a '|'-joined list value (used for arrays like affirmations/quick replies) back into a string[]. */
export const tList = (lang: LanguageCode, key: string): string[] => {
  const dict = DICTS[lang] || en;
  const raw = dict[key] ?? en[key] ?? '';
  return raw.split('|');
};
